function initialLanguage(): SupportedLanguage {
  let stored: string | null = null;
  try {
    stored = typeof window.localStorage?.getItem === "function"
      ? window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
      : null;
  } catch {
    // Storage can be unavailable in hardened/embedded browser contexts.
  }
  if (stored === "en" || stored === "zh-CN") return stored;
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage(),
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export async function setApplicationLanguage(language: SupportedLanguage) {
  try {
    if (typeof window.localStorage?.setItem === "function") window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // The in-memory i18n state still changes when persistence is unavailable.
  }
  document.documentElement.lang = language;
  await i18n.changeLanguage(language);
}

document.documentElement.lang = i18n.language;

